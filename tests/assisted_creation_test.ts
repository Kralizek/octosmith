Deno.test("explicit names ignore unused naming strategies but retain name validation", async () => {
  const loaded = withTemplate(
    configuration({
      names: ["api-*", "svc-*"],
      visibility: "private",
    }, { names: ["api-reserved"] }),
    { match: { include: { names: ["api-*"] } } },
  );
  for (const namingStrategy of ["api-*", "untrusted-*", "svc-*", ""]) {
    for (
      const name of [
        "api-orders",
        "../invalid",
        "",
        "svc-orders",
        "api-reserved",
      ]
    ) {
      const input = { template: "services", name };
      const options = {
        randomBytes: () => {
          throw new Error("Explicit names must not generate");
        },
      };
      const expected = await preflightRepositoryCreation(
        loaded,
        input,
        options,
      );
      const result = await preflightRepositoryCreation(
        loaded,
        { ...input, namingStrategy },
        options,
      );
      assertEquals(result.ready, name === "api-orders");
      assertEquals(result.choices, expected.choices);
      assertEquals(result.diagnostics, expected.diagnostics);
      assertEquals(result.repository, expected.repository);
      assertEquals(result.inputs.namingStrategy, namingStrategy);
    }
  }
});

Deno.test("selected strategy retains bounded exclude retries and classification checks", async () => {
  const loaded = configuration(
    { names: ["api-*", "svc-*"], visibility: "private" },
    { names: ["api-aaaaaa"] },
  );
  let calls = 0;
  const selected = { template: "services", namingStrategy: "api-*" };
  const result = await preflightRepositoryCreation(loaded, selected, {
    maxNameAttempts: 2,
    randomBytes: (length) => new Uint8Array(length).fill(calls++ === 0 ? 0 : 1),
  });
  assertEquals(result.ready, true);
  assertEquals(result.repository?.name, "api-bbbbbb");
  assertEquals(calls, 2);

  const failed = await preflightRepositoryCreation(loaded, selected, {
    maxNameAttempts: 2,
    randomBytes: (length) => new Uint8Array(length),
  });
  assertEquals(failed.ready, false);
  assertEquals(failed.choices.name.status, "generation_failed");

  const overlapping = withTemplate(loaded, {}, {
    "repository:other": {
      version: 1,
      kind: "repository",
      match: { include: { names: ["svc-*"] } },
      repository: {},
    },
  });
  const overlap = await preflightRepositoryCreation(overlapping, {
    ...selected,
    namingStrategy: "svc-*",
  }, { randomBytes: (length) => new Uint8Array(length) });
  assertEquals(overlap.ready, false);
  assertEquals(
    overlap.diagnostics.some(({ code }) => code === "template_overlap"),
    true,
  );
});

