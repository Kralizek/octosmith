function configuration(
  include: RepositorySelector | "all" = {
    names: ["api-*"],
    visibility: "private",
  },
  exclude?: RepositorySelector,
): LoadedConfiguration {
  return {
    root: ".",
    configuration: {
      version: 1,
      organization: "acme",
      repositories: { scope: { include, ...(exclude && { exclude }) } },
    },
    templates: {
      "repository:services": {
        version: 1,
        kind: "repository",
        match: { include: "all" },
        repository: {},
      },
    },
  };
}

function withTemplate(
  loaded: LoadedConfiguration,
  changes: Partial<RepositoryTemplate>,
  others: Record<string, RepositoryTemplate> = {},
): LoadedConfiguration {
  return {
    ...loaded,
    templates: {
      ...loaded.templates,
      "repository:services": {
        ...loaded.templates["repository:services"],
        ...changes,
      },
      ...others,
    },
  };
}

function interaction(answers: readonly (string | null)[]) {
  const questions: string[] = [];
  const errors: string[] = [];
  let index = 0;
  const prompts: CreationPromptAdapter = {
    prompt(message) {
      questions.push(message);
      if (index >= answers.length) {
        throw new Error("Unexpected prompt: " + message);
      }
      return Promise.resolve(answers[index++]);
    },
  };
  return { prompts, questions, errors };
}

async function resolve(
  loaded: LoadedConfiguration,
  answers: readonly (string | null)[],
  input: RepositoryCreationInput = { template: "services" },
) {
  const terminal = interaction(answers);
  let randomCalls = 0;
  const specification = await resolveAssistedRepositoryCreation(
    loaded,
    input,
    terminal.prompts,
    (message) => terminal.errors.push(message),
    {
      randomBytes: (length) => {
        randomCalls++;
        return new Uint8Array(length);
      },
    },
  );
  return { specification, randomCalls, ...terminal };
}

Deno.test("assisted visibility offers only effective alternatives with readable descriptions", async () => {
  const result = await resolve(
    configuration({ names: ["api-*"], visibility: ["private", "internal"] }),
    ["2"],
  );
  assertEquals(result.specification.ready, true);
  assertEquals(result.specification.repository?.visibility, "internal");
  assertEquals(result.questions.length, 1);
  assertStringIncludes(result.questions[0], "1. Private");
  assertStringIncludes(result.questions[0], "2. Internal");
  assertEquals(result.questions[0].includes("Public"), false);
  assertEquals(result.randomCalls, 1);
});

