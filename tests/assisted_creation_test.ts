for (
  const { title, input, close, expected } of [
    {
      title: "CRLF and successive lines",
      input: "orders\r\nnext\n",
      close: false,
      expected: ["orders", "next"],
    },
    {
      title: "EOF discards unfinished input",
      input: "unfinished",
      close: false,
      expected: [null, null],
    },
    { title: "closed stdin", input: "", close: true, expected: [null, null] },
  ]
) {
  Deno.test(
    "terminal prompt adapter uses stderr and handles " + title,
    async () => {
      const adapter =
        new URL("../packages/cli/assisted.ts", import.meta.url).href;
      const child = new Deno.Command(Deno.execPath(), {
        args: [
          "eval",
          `
        import { terminalCreationPrompts } from ${JSON.stringify(adapter)};
        ${close ? "Deno.stdin.close();" : ""}
        const first = await terminalCreationPrompts.prompt("First question");
        const second = await terminalCreationPrompts.prompt("Second question");
        console.log(JSON.stringify([first, second]));
      `,
        ],
        stdin: "piped",
        stdout: "piped",
        stderr: "piped",
      }).spawn();
      const writer = child.stdin.getWriter();
      if (input) await writer.write(new TextEncoder().encode(input));
      await writer.close();
      const result = await child.output();
      const decoder = new TextDecoder();
      assertEquals(result.code, 0, decoder.decode(result.stderr));
      assertEquals(JSON.parse(decoder.decode(result.stdout)), expected);
      assertStringIncludes(decoder.decode(result.stderr), "First question");
      assertStringIncludes(decoder.decode(result.stderr), "Second question");
    },
  );
}
