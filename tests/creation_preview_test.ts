Deno.test("resource create JSON redacts parser snippets and schema-invalid values", async () => {
  const root = await Deno.makeTempDir();
  try {
    for (
      const content of [
        "version: 1\norganization: [PRIVATE_PARSER_SENTINEL\n",
        JSON.stringify({
          version: 1,
          organization: "acme",
          repositories: {
            scope: { include: { visibility: "PRIVATE_SCHEMA_SENTINEL" } },
          },
        }),
      ]
    ) {
      await Deno.writeTextFile(root + "/octosmith.yml", content);
      const output: string[] = [];
      const errors: string[] = [];
      assertEquals(
        await main([
          "resource",
          "create",
          "services",
          "--path",
          root,
          "--dry-run",
          "--format",
          "json",
        ], {
          write: (value) => output.push(value),
          writeError: (value) => errors.push(value),
        }),
        1,
      );
      assertEquals(
        JSON.parse(output.join("\n")).diagnostics[0].code,
        "configuration_load_error",
      );
      assertEquals(errors, []);
      assertEquals(output.join("\n").includes("PRIVATE_"), false);
    }
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});
