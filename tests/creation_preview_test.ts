Deno.test({
  name:
    "resource create dry-run renders valid JSON on success and failure offline with no writes, credentials, or Git",
  permissions: { read: true, write: false, net: false, env: false, run: false },
  fn: async () => {
    for (
      const { args, ready, code } of [
        {
          args: ["--name", "team-orders-svcs", "--visibility", "internal"],
          ready: true,
          code: undefined,
        },
        { args: ["--visibility", "private"], ready: true, code: undefined },
        { args: [], ready: false, code: "visibility_ambiguous" },
        {
          args: ["--name", "bad/name", "--visibility", "private"],
          ready: false,
          code: "invalid_name",
        },
        {
          args: ["--visibility", "invalid"],
          ready: false,
          code: "invalid_visibility",
        },
      ]
    ) {
      const output: string[] = [];
      const errors: string[] = [];
      let forbiddenCalls = 0;
      const forbidden = (): never => {
        forbiddenCalls++;
        throw new Error("Preview must not access credentials or GitHub");
      };
      assertEquals(
        await main(
          [
            "resource",
            "create",
            "services",
            "--path",
            fixture,
            "--dry-run",
            "--format",
            "json",
            ...args,
          ],
          {
            credentials: { getEnv: forbidden, runGhAuthToken: forbidden },
            bootstrap: { bootstrap: forbidden },
            fetch: forbidden,
            write: (value) => output.push(value),
            writeError: (value) => errors.push(value),
          },
        ),
        ready ? 0 : 1,
      );
      const result = JSON.parse(output.join("\n")) as RepositoryCreationPreview;
      assertEquals(result.kind, "repository_creation_preview");
      assertEquals(result.ready, ready);
      assertEquals(result.version, 1);
      if (code !== undefined) {
        assertEquals(
          result.diagnostics.some((issue) => issue.code === code),
          true,
        );
        assertEquals(result.identity, undefined);
      } else {
        const loaded = await loadConfigurationDirectory(fixture);
        const expected = await preview(loaded, {
          template: "services",
          name: result.identity!.name,
          visibility: result.identity!.visibility,
        });
        assertEquals(result.bootstrap, expected.bootstrap);
        assertEquals(result.resources, expected.resources);
      }
      assertEquals(errors, []);
      assertEquals(forbiddenCalls, 0);
      assertEquals(
        output.join("\n").includes("PRIVATE_LITERAL_SENTINEL"),
        false,
      );
      assertEquals(
        output.join("\n").includes("MANAGED_FILE_CONTENT_SENTINEL"),
        false,
      );
    }
  },
});

