const fixture = "tests/fixtures/creation-preview";

function configuration(
  include: RepositorySelector | "all" = {
    names: ["team-*-svcs"],
    visibility: "internal",
    teams: ["platform"],
    properties: { tier: "backend" },
  },
): LoadedConfiguration {
  return {
    root: ".",
    configuration: {
      version: 1,
      organization: "acme",
      repositories: { scope: { include } },
    },
    templates: {
      "repository:services": {
        version: 1,
        kind: "repository",
        match: { include: "all" },
        repository: {},
      },
    },
  };
}

async function preview(
  loaded: LoadedConfiguration,
  input: RepositoryCreationInput = { template: "services" },
): Promise<RepositoryCreationPreview> {
  const specification = await preflightRepositoryCreation(loaded, input, {
    randomBytes: (length) => new Uint8Array(length),
  });
  return buildRepositoryCreationPreview(loaded, specification);
}

Deno.test({
  name:
    "creation preview resolves explicit identity and defers remote branch and reconciliation",
  permissions: {
    read: false,
    write: false,
    net: false,
    env: false,
    run: false,
  },
  fn: async () => {
    const result = await preview(configuration(), {
      template: "services",
      name: "team-orders-svcs",
      visibility: "internal",
    });
    assertEquals(result.ready, true);
    assertEquals(result.identity, {
      name: "team-orders-svcs",
      visibility: "internal",
      nameOrigin: "explicit",
      nameProvisional: false,
      nameNotice:
        "Explicit name; availability must still be checked during execution.",
    });
    assertEquals(result.requirements, {
      teams: ["platform"],
      customProperties: { tier: "backend" },
    });
    assertEquals(result.bootstrap?.defaultBranch.status, "deferred");
    if (result.bootstrap?.defaultBranch.status === "deferred") {
      assertEquals(result.bootstrap.defaultBranch.precedence, [
        "organization",
        "github_fallback",
      ]);
    }
    assertEquals(result.bootstrap?.files, []);
    assertEquals(result.bootstrap?.plannedFileCount, 0);
    assertEquals(
      result.resources.map(({ category, status }) => [category, status]),
      [
        ["settings", "not_applicable"],
        ["teams", "not_applicable"],
        ["custom_properties", "not_applicable"],
        ["actions", "not_applicable"],
        ["dependabot", "not_applicable"],
        ["environments", "not_applicable"],
        ["rulesets", "not_applicable"],
      ],
    );
    assertEquals(result.deferred.map(({ code }) => code), [
      "repository_availability",
      "classification_verification",
      "github_reconciliation",
    ]);
    const text = renderRepositoryCreationPreview(result);
    for (
      const value of [
        "acme",
        "repository:services",
        "team-orders-svcs",
        "explicit",
        "internal",
        "platform",
        "backend",
        "Default branch: deferred",
        "not_applicable",
      ]
    ) assertStringIncludes(text, value);
    assertEquals(
      JSON.parse(renderOutput("json", result, renderRepositoryCreationPreview)),
      result,
    );
  },
});

Deno.test("generated preview names are provisional, unreserved, and never regenerated by the builder", async () => {
  const loaded = configuration();
  let calls = 0;
  const specification = await preflightRepositoryCreation(
    loaded,
    { template: "services" },
    {
      randomBytes: (length) => {
        calls++;
        return new Uint8Array(length);
      },
    },
  );
  const result = buildRepositoryCreationPreview(loaded, specification);
  assertEquals(result.identity?.name, "team-aaaaaa-svcs");
  assertEquals(result.identity?.nameOrigin, "generated");
  assertEquals(result.identity?.nameProvisional, true);
  assertStringIncludes(result.identity!.nameNotice, "not reserved");
  assertStringIncludes(renderRepositoryCreationPreview(result), "--name");
  assertEquals(buildRepositoryCreationPreview(loaded, specification), result);
  assertEquals(calls, 1);
});

Deno.test("creation preview preserves structured ambiguities and invalid metadata without generating names", async () => {
  const cases: readonly {
    include: RepositorySelector | "all";
    input: RepositoryCreationInput;
    code: string;
  }[] = [
    {
      include: {
        names: ["team-*-svcs"],
        visibility: ["private", "internal"],
      },
      input: { template: "services" },
      code: "visibility_ambiguous",
    },
    {
      include: {
        names: ["team-*", "app-*"],
        visibility: "private",
      },
      input: { template: "services" },
      code: "ambiguous_name_strategy",
    },
    {
      include: "all",
      input: { template: "services", visibility: "private" },
      code: "name_required",
    },
    {
      include: { visibility: "private", properties: { tier: "backend" } },
      input: {
        template: "services",
        name: "api",
        properties: { tier: "frontend" },
      },
      code: "property_conflict",
    },
    {
      include: { visibility: "private" },
      input: { template: "services", name: "api", visibility: "internal" },
      code: "invalid_visibility",
    },
    {
      include: "all",
      input: { template: "services", name: "../invalid" },
      code: "invalid_name",
    },
  ];
  for (const { include, input, code } of cases) {
    const loaded = configuration(include);
    let calls = 0;
    const specification = await preflightRepositoryCreation(loaded, input, {
      randomBytes: (length) => {
        calls++;
        return new Uint8Array(length);
      },
    });
    const result = buildRepositoryCreationPreview(loaded, specification);
    assertEquals(result.ready, false);
    assertEquals(result.identity, undefined);
    assertEquals(result.bootstrap, undefined);
    assertEquals(result.resources, []);
    assertEquals(result.choices, specification.choices);
    assertEquals(result.diagnostics, specification.diagnostics);
    assertEquals(result.diagnostics.some((issue) => issue.code === code), true);
    assertStringIncludes(renderRepositoryCreationPreview(result), code);
    assertEquals(JSON.parse(JSON.stringify(result)).ready, false);
    assertEquals(calls, 0);
  }
});

Deno.test("creation preview rejects incompatible composed settings and malformed ready specifications", async () => {
  const loaded = configuration();
  const conflicting: LoadedConfiguration = {
    ...loaded,
    templates: {
      "repository:services": {
        ...loaded.templates["repository:services"],
        repository: { settings: { visibility: "public" } },
      },
    },
  };
  const result = await preview(conflicting);
  assertEquals(result.ready, false);
  assertEquals(
    result.diagnostics.some(({ code }) => code === "incompatible_constraints"),
    true,
  );
  const unreachable = await preview({
    ...loaded,
    templates: {
      "repository:services": {
        ...loaded.templates["repository:services"],
        match: { include: { visibility: "public" } },
      },
    },
  });
  assertEquals(unreachable.ready, false);
  assertEquals(
    unreachable.diagnostics.some(({ code }) => code === "template_unreachable"),
    true,
  );
  const valid = await preflightRepositoryCreation(loaded, {
    template: "services",
    name: "team-orders-svcs",
  });
  assertThrows(() =>
    buildRepositoryCreationPreview(loaded, { ...valid, repository: undefined })
  );
});

